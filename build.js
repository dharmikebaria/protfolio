const blogDir = path.join(ROOT, 'blog');
fs.readdirSync(blogDir, { withFileTypes: true })
  .filter(d => d.isDirectory() && fs.existsSync(path.join(blogDir, d.name, 'index.html')))
  .filter(d => !/content="noindex/.test(fs.readFileSync(path.join(blogDir, d.name, 'index.html'), 'utf8')))
