#!/usr/bin/env node
/* =====================================================================
   build.js — static page generator (no dependencies, Node 18+)

   Run:  node build.js

   Reads the <style> block and the PROJECT DATA from project.html and writes:
     projects/index.html              all-projects listing
     projects/<slug>/index.html       one crawlable page per project
     404.html                         custom not-found page
     blog/_template.html              starter for future articles (noindex)
     sitemap.xml                      homepage, projects, published blog posts, resume

   The generated files are committed, so Vercel needs no build settings.
   Re-run this after editing project text or styles in project.html, or
   after adding a blog post folder (blog/<slug>/index.html).
   ===================================================================== */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { execSync } = require('child_process');

const ROOT = __dirname;
const SITE = 'https://www.dharmikbaria.online';
const NAME = 'Dharmike Baria';
const GH = 'https://github.com/dharmikebaria';
const OG_IMAGE = SITE + '/og-image.jpg';
const TODAY = new Date().toISOString().slice(0, 10);

/* ---------- read the source ---------- */
const src = fs.readFileSync(path.join(ROOT, 'project.html'), 'utf8').replace(/\r\n/g, '\n');
const css = (src.match(/^<style>$([\s\S]*?)^<\/style>$/m) || [])[1];
const data = (src.match(/\/\* BUILD:DATA-START[\s\S]*?\/\* BUILD:DATA-END \*\//) || [])[0];
if (!css || !data) throw new Error('Could not find the <style> block or the BUILD:DATA markers in project.html');
const PROJECTS = vm.runInNewContext(data + '\n;PROJECTS', {});

/* ---------- helpers ---------- */
const pad = (n) => String(n).padStart(2, '0');
/* escape for attribute values and <title> */
const esc = (s) => String(s).replace(/&(?![a-z#0-9]+;)/gi, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
/* body text: the data may already contain entities, so only fix bare ampersands */
const t = (s) => String(s).replace(/&(?![a-z#0-9]+;)/gi, '&amp;');
const plain = (s) => String(s).replace(/&amp;/g, '&');
const ld = (obj) => `<script type="application/ld+json">\n${JSON.stringify(obj, null, 2).replace(/</g, '\\u003c')}\n</script>`;

function clip(s, max) {
  if (s.length <= max) return s;
  const cut = s.slice(0, max - 1);
  return cut.slice(0, cut.lastIndexOf(' ')).replace(/[\s,;:—–-]+$/, '') + '…';
}
function projectTitle(p) {
  const long = `${p.title} — ${p.type} Project | ${NAME}`;
  return plain(long).length <= 60 ? long : `${p.title} | ${NAME}`;
}
function projectDesc(p) {
  const tail = ` Case study by ${NAME}, Python Developer.`;
  const s = plain(p.summary);
  return s.length + tail.length <= 158 ? s + tail : clip(s, 158);
}
function gitDate(file) {
  try {
    const d = execSync(`git log -1 --format=%cs -- "${file}"`, { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
    return /^\d{4}-\d{2}-\d{2}$/.test(d) ? d : TODAY;
  } catch (e) { return TODAY; }
}
function write(rel, html) {
  const file = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, html);
  console.log('wrote', rel);
}

